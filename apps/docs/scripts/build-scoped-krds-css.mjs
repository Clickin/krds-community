/**
 * Generates src/styles/krds-chrome-scoped.css from @krds-community/styles.
 *
 * The KRDS foundation CSS assumes it owns the page: an unlayered Eric-Meyer
 * reset and `html { font-size: 62.5% }`. Imported as-is into Starlight it
 * collapses every rem and wipes prose spacing. This script re-scopes the
 * upstream CSS so it only applies inside the KRDS chrome components
 * (#krds-masthead, #krds-footer) embedded in the docs chrome:
 *
 *   - global at-rules (@font-face, @keyframes) are hoisted untouched
 *   - :root/html/body selectors become :scope
 *   - everything else is wrapped in @scope (#krds-masthead, #krds-footer)
 *
 * rem sizing inside the scope still resolves against the 16px document root;
 * theme.css compensates with `zoom: 0.625` on .krds-docs-chrome wrappers.
 *
 * Generated file — do not edit by hand. Re-run: node scripts/build-scoped-krds-css.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const postcss = require("postcss");

const stylesPath = require.resolve("@krds-community/styles/css", {
  paths: [fileURLToPath(new URL("..", import.meta.url))],
});
const outPath = fileURLToPath(new URL("../src/styles/krds-chrome-scoped.css", import.meta.url));

const root = postcss.parse(readFileSync(stylesPath, "utf8"), { from: stylesPath });

const SCOPE = "(#krds-masthead, #krds-footer)";
/** @type {string[]} */
const hoisted = [];
/** @type {string[]} */
const scoped = [];

/** @param {string} selector */
const rewriteSelector = (selector) =>
  selector
    .split(",")
    .map((part) => {
      const trimmed = part.trim();
      if (
        trimmed === ":root" ||
        trimmed === "html" ||
        trimmed === "body" ||
        trimmed === "html body"
      )
        return ":scope";
      if (/^html\s+/.test(trimmed)) return `:scope ${trimmed.slice(5)}`;
      if (/^body\s+/.test(trimmed)) return `:scope ${trimmed.slice(5)}`;
      return trimmed;
    })
    .join(", ");

/** @param {any} node */
const processNode = (node) => {
  if (
    node.type === "atrule" &&
    ["font-face", "keyframes", "-webkit-keyframes"].includes(node.name)
  ) {
    hoisted.push(node.toString());
    return;
  }
  if (node.type === "atrule" && node.name === "charset") return;
  if (node.type === "atrule" && node.nodes) {
    const clone = node.clone().removeAll();
    for (const child of node.nodes) {
      if (child.type === "rule") {
        child.selector = rewriteSelector(child.selector);
        clone.append(child.clone());
      } else if (child.type === "atrule" && ["font-face", "keyframes"].includes(child.name)) {
        hoisted.push(child.toString());
      } else {
        clone.append(child.clone());
      }
    }
    scoped.push(clone.toString());
    return;
  }
  if (node.type === "rule") {
    node.selector = rewriteSelector(node.selector);
    scoped.push(node.toString());
    return;
  }
  if (node.type === "decl") {
    // top-level declarations (custom property fallbacks) — keep at scope root
    scoped.push(`:scope { ${node.toString()} }`);
    return;
  }
  // comments and stray nodes: skip
};

for (const node of root.nodes) processNode(node);

const output = [
  "/* GENERATED by scripts/build-scoped-krds-css.mjs — do not edit. */",
  `/* Source: @krds-community/styles/css, scoped to ${SCOPE}. */`,
  ...hoisted,
  `@scope ${SCOPE} {`,
  ...scoped,
  "}",
  "",
].join("\n");

writeFileSync(outPath, output);
console.log(`Wrote ${outPath} (${hoisted.length} hoisted at-rules, ${scoped.length} scoped rules)`);
